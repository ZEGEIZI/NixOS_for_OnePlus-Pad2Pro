#!/usr/bin/env python3
"""kShimC boot entry installer for NixOS (kShimC 启动项安装器).

Install a NixOS generation's boot files and configuration using the independent
kShimC boot protocol, and retain its Nix store dependencies with GC roots.
"""
import argparse
import contextlib
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
from types import SimpleNamespace

from kshim_protocol import protocol


def boot_spec(system, offline=False):
    system = system.resolve(strict=True)
    if not offline and not re.fullmatch(r"/nix/store/[a-z0-9]{32}-[^/]+", str(system)):
        raise ValueError("Expected a realised NixOS system in /nix/store")
    document = json.loads((system / "boot.json").read_text())
    spec = document["org.nixos.bootspec.v1"]
    device = document["org.oneplus.pad2pro.v1"]
    if spec["system"] != "aarch64-linux" or Path(spec["toplevel"]).resolve() != system:
        raise ValueError("Bootspec must describe this ARM64 system")
    if spec["init"] != str(system / "init") or not (system / "init").is_file():
        raise ValueError("Bootspec init must belong to the selected system")
    if spec.get("initrdSecrets"):
        raise ValueError("kShimC does not support initrd secrets")
    params = spec["kernelParams"]
    if not isinstance(params, list) or any(
        not isinstance(p, str) or not p or any(c.isspace() or ord(c) < 32 for c in p)
        or p.startswith("init=") for p in params
    ):
        raise ValueError("Invalid kernel parameters; init= is generated by the installer")
    cmdline = " ".join(params + ["init=" + spec["init"]])
    protocol.plain(cmdline, 4096)
    paths = [Path(spec["kernel"]), Path(device["dtb"]), Path(spec["initrd"])]
    for path in paths:
        if not path.is_absolute() or not path.resolve(strict=True).is_file():
            raise ValueError("Missing absolute boot payload")
    compatible = subprocess.check_output([
        "fdtget", str(paths[1].resolve()), "/", "compatible"
    ], text=True).split()
    if not {"oneplus,opd2413", "qcom,sm8750"} <= set(compatible):
        raise ValueError("DTB is incompatible with the pinned kShimC protocol")
    identity = hashlib.sha256((str(system) + json.dumps(document, sort_keys=True)).encode()).hexdigest()[:32]
    return system, spec, device, paths, cmdline, "nixos-" + identity


def merge_shared_config(boot):
    kshim = protocol.directory(boot / "kshim")
    with protocol.locked(kshim / ".config.lock"):
        path = kshim / "boot.conf"
        if path.exists():
            old = protocol.read_config(path, ("format", "systems", "default", "timeout_ms"))
            systems = old["systems"].split(",")
            if "nixos" in systems:
                return
            if len(systems) >= 4:
                raise ValueError("Shared kShimC system menu is full")
            systems.append("nixos")
            default, timeout = old["default"], old["timeout_ms"]
        else:
            systems, default, timeout = ["nixos"], "android", "8000"
        protocol.atomic_text(path, f"format=1\nsystems={','.join(systems)}\ndefault={default}\ntimeout_ms={timeout}\n")


@contextlib.contextmanager
def boot_mount(args):
    # Serialize remounts as well as publication. A lock inside /boot alone
    # allows another process to restore ro while the first is still writing.
    guard = contextlib.nullcontext() if args.staging_root else protocol.locked(Path("/run/lock/nixos-kshim.lock"))
    with guard:
        with mounted_boot(args) as boot:
            yield boot


@contextlib.contextmanager
def mounted_boot(args):
    if args.staging_root:
        yield protocol.root(SimpleNamespace(staging_root=args.staging_root))
        return
    boot = args.boot_dir.absolute()
    if not args.partuuid:
        raise ValueError("Live installation requires the actual --partuuid; set boot.loader.kshim.bootPartuuid")
    if boot.is_symlink() or boot.resolve() != boot:
        raise ValueError("Boot mount path must not contain symlinks")
    mounts = json.loads(subprocess.check_output([
        "findmnt", "--json", "--mountpoint", str(boot), "-o",
        "TARGET,SOURCE,FSTYPE,OPTIONS,PARTUUID,PARTLABEL,FSROOT"
    ], text=True))["filesystems"]
    if len(mounts) != 1:
        raise ValueError("Expected exactly one boot mount")
    mount = mounts[0]
    if (mount["target"] != str(boot) or mount["fstype"] != "ext4"
            or mount["fsroot"] != "/" or mount.get("partlabel") != args.partlabel
            or (mount.get("partuuid") or "").lower() != args.partuuid.lower()):
        raise ValueError("Boot partition identity/filesystem mismatch")
    readonly = "ro" in mount["options"].split(",")
    if readonly:
        subprocess.run(["mount", "-o", "remount,rw", str(boot)], check=True)
    try:
        yield protocol.root(SimpleNamespace(
            staging_root=None, boot_dir=boot, partuuid=args.partuuid, action="publish"))
    finally:
        # Always leave the boot filesystem clean and read-only, including
        # when migrating an installation whose old fstab mounted it rw.
        # A writable ext4 mount sets needs_recovery even with no pending
        # writes; kShimC rejects that flag after a forced reset.
        try:
            os.sync()
        finally:
            subprocess.run(["mount", "-o", "remount,ro", str(boot)], check=True)


def protect_system(system, boot_id, offline, boot):
    roots = boot / ".nixos-gcroots" if offline else Path("/nix/var/nix/gcroots/kshim-nixos")
    roots.mkdir(parents=True, exist_ok=True)
    root = roots / boot_id
    if root.is_symlink():
        if root.resolve() != system:
            raise ValueError("GC root identity mismatch")
        return
    if offline:
        root.symlink_to(system)
    else:
        subprocess.run(["nix-store", "--add-root", str(root), "--realise", str(system)], check=True)
    protocol.sync_dir(roots)


def install(args):
    system, spec, device, paths, cmdline, boot_id = boot_spec(args.system, bool(args.staging_root))
    title = spec.get("label") or "NixOS"
    # The boot protocol bounds UTF-8 bytes, while labels may contain Unicode.
    title = title.encode("utf-8")[:95].decode("utf-8", errors="ignore").strip()
    protocol.plain(title, 95)
    reused_payloads = []
    with boot_mount(args) as boot:
        # Serialise this installer's publication/GC-root/config sequence.
        # Protocol locks additionally coordinate with other kShimC publishers.
        with protocol.locked(boot / ".nixos-install.lock"):
            protect_system(system, boot_id, bool(args.staging_root), boot)
            protocol.directory(boot / "kshim")
            systems = protocol.directory(boot / "kshim/systems")
            target = protocol.directory(systems / "nixos")
            protocol.directory(target / "versions")
            with protocol.locked(target / ".update.lock"):
                old = protocol.versions(target)
                present = (target / "versions" / boot_id).exists()
                if present:
                    existing = protocol.version_manifest(target, boot_id)
                    if existing["cmdline"] != cmdline:
                        raise ValueError("Existing generation has a different command line")
                    if not old or old["current"] != boot_id:
                        listed = [boot_id] + [v for v in (old["versions"] if old else []) if v != boot_id]
                        protocol.write_versions(target, boot_id, old["current"] if old else "none", listed)
            if not present:
                # Keep command-line scratch files off the boot filesystem.
                import tempfile
                with tempfile.TemporaryDirectory(prefix="nixos-kshim-") as scratch:
                    command_file = Path(scratch) / "cmdline"
                    command_file.write_text(cmdline + "\n")
                    result = protocol.publish(SimpleNamespace(
                        system="nixos", version=boot_id, title=title,
                        kernel_release=device["kernelRelease"], cmdline_file=command_file,
                        image=paths[0].resolve(), dtb=paths[1].resolve(), initrd=paths[2].resolve()
                    ), boot, reuse_payloads=True)
                    reused_payloads = result['reused_payloads']
            merge_shared_config(boot)
    return {"system": str(system), "boot_id": boot_id, "android_boot_written": False,
            "reused_payloads": reused_payloads}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("system", type=Path)
    target = parser.add_mutually_exclusive_group()
    target.add_argument("--boot-dir", type=Path, default=Path("/boot"))
    target.add_argument("--staging-root", type=Path)
    parser.add_argument("--partuuid")
    parser.add_argument("--partlabel", default="KShinC_BOOT")
    args = parser.parse_args()
    try:
        print(json.dumps(install(args), sort_keys=True))
    except (ValueError, OSError, KeyError, subprocess.CalledProcessError) as error:
        parser.exit(1, f"kShimC installation failed: {error}\n")


if __name__ == "__main__":
    main()
